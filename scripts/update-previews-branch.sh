#!/usr/bin/env bash
# Store one pull-request build on the gh-pages-previews branch.
# That branch is not served by itself. The Pages artifact copies pr-<number>/ out of it.
set -euo pipefail

: "${PREVIEW_ACTION:?}"
: "${PR_NUMBER:?}"

if ! [[ "$PR_NUMBER" =~ ^[0-9]+$ ]]; then
  echo "Bad pull request number: $PR_NUMBER" >&2
  exit 1
fi

wt=/tmp/gh-pages-previews
git worktree remove --force "$wt" >/dev/null 2>&1 || true
rm -rf "$wt"
git worktree prune
git fetch origin gh-pages-previews >/dev/null 2>&1 || true

if git show-ref --verify --quiet refs/remotes/origin/gh-pages-previews; then
  git worktree add -B gh-pages-previews "$wt" origin/gh-pages-previews
elif git show-ref --verify --quiet refs/heads/gh-pages-previews; then
  git worktree add "$wt" gh-pages-previews
else
  git worktree add --detach "$wt" HEAD
  git -C "$wt" checkout --orphan gh-pages-previews
  git -C "$wt" rm -rf . >/dev/null 2>&1 || true
  find "$wt" -mindepth 1 -maxdepth 1 ! -name '.git' -exec rm -rf {} +
fi

dest="${wt}/pr-${PR_NUMBER}"
rm -rf "$dest"
if [[ "$PREVIEW_ACTION" != "closed" ]]; then
  if [[ ! -f "${PREVIEW_DIST:-}/index.html" ]]; then
    echo "Preview dist is missing index.html (${PREVIEW_DIST:-unset})" >&2
    exit 1
  fi
  mkdir -p "$dest"
  cp -a "${PREVIEW_DIST}/." "$dest/"
  rm -f "${dest}/CNAME"
fi

cat >"${wt}/README.md" <<'EOF'
# PR previews

Generated by the Publish PR preview workflow. Each `pr-<number>/` directory is one pull request build. Do not edit this branch by hand.
EOF
touch "${wt}/.nojekyll"

git -C "$wt" add -A
if git -C "$wt" diff --cached --quiet; then
  echo "Preview branch already matches pull request #${PR_NUMBER}"
  exit 0
fi

git -C "$wt" \
  -c user.name='github-actions[bot]' \
  -c user.email='41898282+github-actions[bot]@users.noreply.github.com' \
  commit -m "Update preview for pull request #${PR_NUMBER}"

if [[ "${DRY_RUN:-}" == "1" ]]; then
  echo "Dry run: not pushing gh-pages-previews"
  exit 0
fi

git -C "$wt" push origin "HEAD:gh-pages-previews"
